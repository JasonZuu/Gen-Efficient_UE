import torch
from torch.utils.data import Dataset
import polars as pl
import numpy as np
from typing import Any, Callable, Dict, List, Optional, Tuple

from metaue_src.label_functions import (
    LABEL_FUNCTIONS,
    LABEL_FN_NEEDS_LOGITS,
)


class MetaUEDataset(Dataset):
    """Dataset for MetaUE training.

    Each sample is either:
    - (embedding_tensor, label_tensor) when precomputed_embeddings is provided
    - (input_ids, attention_mask, label_tensor) otherwise

    Labels are generated by a pluggable label function. Samples with None labels are dropped.
    Labels are always raw continuous float scores (regression mode).
    """

    def __init__(
        self,
        result_df: pl.DataFrame,
        logits_df: Optional[pl.DataFrame],
        label_fn_name: str,
        label_fn_kwargs: Dict[str, Any],
        correct_fn: Optional[Callable] = None,
        response_idx: int = 0,
        tokenizer: Optional[Any] = None,
        precomputed_embeddings: Optional[torch.Tensor] = None,
        max_length: int = 512,
    ):
        self.use_embeddings = precomputed_embeddings is not None
        self.calibrated_threshold: Optional[float] = None
        self.label_norm_params: Optional[Tuple[float, float]] = None
        self.is_regression: bool = True

        label_fn = LABEL_FUNCTIONS[label_fn_name]
        needs_logits = LABEL_FN_NEEDS_LOGITS.get(label_fn_name, False)

        kwargs = dict(label_fn_kwargs)

        result_rows = result_df.to_dicts()
        logits_rows = logits_df.to_dicts() if (logits_df is not None and needs_logits) else [None] * len(result_rows)
        prompts = result_df.get_column("prompt").to_list()

        valid_indices: List[int] = []
        labels: List[float] = []

        for i, row in enumerate(result_rows):
            logits_row = logits_rows[i] if logits_rows else None
            lbl = label_fn(row, logits_row, response_idx=response_idx, **kwargs)
            if lbl is None:
                continue
            valid_indices.append(i)
            labels.append(float(lbl))

        self.labels = torch.tensor(labels, dtype=torch.float32)

        if self.use_embeddings:
            self.embeddings = precomputed_embeddings[valid_indices]
        else:
            assert tokenizer is not None, "tokenizer required when precomputed_embeddings is None"
            selected_prompts = [prompts[i] for i in valid_indices]
            encoded = tokenizer(
                selected_prompts,
                max_length=max_length,
                truncation=True,
                padding="max_length",
                return_tensors="pt",
            )
            self.input_ids = encoded["input_ids"]
            self.attention_mask = encoded["attention_mask"]

    def __len__(self) -> int:
        return len(self.labels)

    def __getitem__(self, idx: int):
        label = self.labels[idx]
        if self.use_embeddings:
            return self.embeddings[idx], label
        return self.input_ids[idx], self.attention_mask[idx], label

    @classmethod
    def from_labels(
        cls,
        labels: np.ndarray,
        valid_indices: np.ndarray,
        precomputed_embeddings: torch.Tensor,
        calibrated_threshold: Optional[float] = None,
        label_norm_params: Optional[Tuple[float, float]] = None,
    ) -> "MetaUEDataset":
        """Construct a dataset from pre-computed labels (e.g. from the label cache).

        Labels should already be min-max normalised by the caller using training-set
        statistics before being passed here.
        """
        obj = cls.__new__(cls)
        obj.use_embeddings = True
        obj.calibrated_threshold = calibrated_threshold
        obj.label_norm_params: Optional[Tuple[float, float]] = label_norm_params
        obj.is_regression = True
        obj.labels = torch.from_numpy(labels.astype(np.float32))
        obj.embeddings = precomputed_embeddings[valid_indices]
        return obj

    @property
    def label_distribution(self) -> Dict[int, int]:
        labels_list = self.labels.tolist()
        return {
            0: int(sum(1 for l in labels_list if l == 0)),
            1: int(sum(1 for l in labels_list if l == 1)),
        }


def collate_fn_embeddings(batch):
    embeddings = torch.stack([b[0] for b in batch])
    labels = torch.stack([b[1] for b in batch])
    return embeddings, labels


def collate_fn_tokenized(batch):
    input_ids = torch.stack([b[0] for b in batch])
    attention_mask = torch.stack([b[1] for b in batch])
    labels = torch.stack([b[2] for b in batch])
    return input_ids, attention_mask, labels
